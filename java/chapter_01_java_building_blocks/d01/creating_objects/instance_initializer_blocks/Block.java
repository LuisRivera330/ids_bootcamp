package ids_bootcamp.java.chapter_01_java_building_blocks.d01.creating_objects.instance_initializer_blocks;

public class Block {
    public static void main(String[] args) {
        //Cuando esta entre llaves {} se llama "bloque de código"
        //En este ejemplo hay 3 bloques de código
        {
            System.out.println("Feathers");
        }
    }{
        System.out.println("Snowy");
    }
    //Se imprime Feathers porque está dentro del método main
}
