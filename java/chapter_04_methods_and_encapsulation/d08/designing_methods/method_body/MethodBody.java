public class MethodBody {
    //El cupero de un método es simplemente un bloque de código

    public void walk1() { } //Es una declaración de método válida con un cuerpo vacío.
    //public void walk2; // No compila porque e faltan las llaves alrededor del cuerpo vacío
    public void walk3(int a) { int name = 5; }//Es una declaración de método válida con una sola instrucción en el cuerpo.
}
